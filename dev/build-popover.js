#!/usr/bin/env node
/* Makes everything the Mac app carries from the rules in core/, so the app needs nothing else at build time:
 *   app/Resources/popover.html   the popover page with the rules, the readers and the popover's rules inside it
 *   app/Resources/access.html    the App access window's page with its rules inside it
 *   app/Resources/status.js      the rules of the menu-bar label (run in JavaScriptCore, no page)
 *   app/Sources/Scripts.swift    the only AppleScript the app can run, all of it read-only
 * node dev/build-popover.js */
'use strict';
var fs = require('fs'), path = require('path'), root = path.join(__dirname, '..');
function read(p) { return fs.readFileSync(path.join(root, p), 'utf8'); }
function inline(js) { return js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--'); }
function page(template, parts, out) {
  var html = read(template);
  parts.forEach(function (pair) {
    if (html.indexOf(pair[0]) < 0) throw new Error('placeholder missing: ' + pair[0]);
    html = html.split(pair[0]).join(inline(read(pair[1])));
  });
  fs.writeFileSync(path.join(root, 'app', 'Resources', out), html);
  console.log('app/Resources/' + out + '  ' + html.length + ' characters');
}
fs.mkdirSync(path.join(root, 'app', 'Resources'), { recursive: true });
page('core/popover.html', [['/*__RULES__*/', 'core/rules.js'], ['/*__READ__*/', 'core/read.js'], ['/*__POPOVER__*/', 'core/popover.js']], 'popover.html');
page('core/access.html', [['/*__ACCESS__*/', 'core/access.js']], 'access.html');
page('core/settings.html', [['/*__SETTINGS__*/', 'core/settings.js']], 'settings.html');
var status = read('core/rules.js') + '\n' + read('core/status.js');
fs.writeFileSync(path.join(root, 'app', 'Resources', 'status.js'), status);
console.log('app/Resources/status.js  ' + status.length + ' characters');
/* what the app answers the browser extension with: the same rules and readers, and the Insert context rules (run in JavaScriptCore, no page) */
var insert = read('core/rules.js') + '\n' + read('core/read.js') + '\n' + read('core/insert.js');
fs.writeFileSync(path.join(root, 'app', 'Resources', 'insert.js'), insert);
console.log('app/Resources/insert.js  ' + insert.length + ' characters');
/* the browser extension travels inside the app, so that Settings can show its folder */
var extFrom = path.join(root, 'extension'), extTo = path.join(root, 'app', 'Resources', 'composer-extension');
fs.rmSync(extTo, { recursive: true, force: true }); fs.mkdirSync(extTo, { recursive: true });
fs.readdirSync(extFrom).forEach(function (f) { fs.copyFileSync(path.join(extFrom, f), path.join(extTo, f)); });
console.log('app/Resources/composer-extension  ' + fs.readdirSync(extTo).length + ' files');

/* The shell keeps its own copy of the read-only scripts, so a page can only name what to ask, never hand over a script. */
var Core = require('../core/rules.js');
function swiftString(s) {
  var j = JSON.stringify(s);
  if (/\\u[0-9a-fA-F]{4}|\\\/|\\[bfrt]/.test(j)) throw new Error('script text needs an escape Swift does not share with JSON');
  return j;
}
var ids = Object.keys(Core.SELECTION_APPS).sort();
function table(name, value) { return '    static let ' + name + ': [String: String] = [\n' + ids.map(function (b) { return '        ' + swiftString(b) + ': ' + swiftString(value(b)); }).join(',\n') + '\n    ]\n\n'; }
/* the identity of the extension (from the public key in its manifest) and the name of the local helper, for the app */
var manifest = JSON.parse(read('extension/manifest.json')), digest = require('crypto').createHash('sha256').update(Buffer.from(manifest.key, 'base64')).digest('hex').slice(0, 32);
var extensionId = digest.split('').map(function (c) { return String.fromCharCode(97 + parseInt(c, 16)); }).join('');
var hostName = require('../extension/lib.js').HOST;
var swift = '// Generated by dev/build-popover.js from core/rules.js (APPLESCRIPT). Do not edit by hand.\n' +
  '// These are the only scripts the app can run. They read; none of them changes anything in another app.\n' +
  '// "watch" is "selection" with a shorter wait: the menu-bar label asks the same question and gives up after 1 second.\n\n' +
  'enum Scripts {\n' +
  '    /// The browser extension that may ask this app for context (extension/manifest.json), and the name it asks under.\n' +
  '    static let composerExtensionId: String = ' + swiftString(extensionId) + '\n' +
  '    static let composerHostName: String = ' + swiftString(hostName) + '\n\n' +
  table('names', function (b) { return Core.SELECTION_APPS[b]; }) + table('selection', Core.scriptForSelection) + table('watch', Core.scriptForWatch) +
  '    static let readNote: String = ' + swiftString(Core.APPLESCRIPT.readNote) + '\n\n' +
  '    static let readMail: String = ' + swiftString(Core.APPLESCRIPT.readMail) + '\n}\n';
fs.mkdirSync(path.join(root, 'app', 'Sources'), { recursive: true });
fs.writeFileSync(path.join(root, 'app', 'Sources', 'Scripts.swift'), swift);
console.log('app/Sources/Scripts.swift  ' + ids.length + ' selection scripts, ' + ids.length + ' watch scripts, 2 read scripts');
